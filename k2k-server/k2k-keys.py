class Handler(BaseHTTPRequestHandler):
    server_version = "k2k-keys"

    def log_message(self, fmt, *args):
        pass

    def client_ip(self):
        fwd = self.headers.get("X-Forwarded-For", "")
        return (fwd.split(",")[0].strip() if fwd else self.client_address[0]) or "?"

    def send_json(self, code, obj, cookie=None):
        body = json.dumps(obj, ensure_ascii=False).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Cache-Control", "no-store")
        if cookie:
            self.send_header("Set-Cookie", cookie)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def read_json(self):
        try:
            n = min(int(self.headers.get("Content-Length", "0")), 64 * 1024)
            return json.loads(self.rfile.read(n) or b"{}")
        except (ValueError, json.JSONDecodeError):
            return {}

    def session_ok(self):
        c = SimpleCookie(self.headers.get("Cookie", ""))
        tok = c.get("k2k_admin")
        if not tok:
            return False
        with lock:
            exp = sessions.get(tok.value)
            if not exp or exp < time.time():
                sessions.pop(tok.value, None)
                return False
        return True

    # ---- routes ----
    def do_GET(self):
        u = urlparse(self.path)
        if u.path in ("/admin", "/admin/"):
            body = ADMIN_HTML.encode()
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Frame-Options", "DENY")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
        elif u.path == "/api/status":
            dev_id = clean_text(parse_qs(u.query).get("id", [""])[0], 40)
            with db() as c:
                row = c.execute(
                    "SELECT k.active FROM devices d JOIN keys k ON d.key=k.key WHERE d.id=?",
                    (dev_id,),
                ).fetchone()
                if row:
                    c.execute("UPDATE devices SET last_seen=? WHERE id=?", (int(time.time()), dev_id))
            self.send_json(200, {
                "registered": bool(row),
                "active": bool(row and row["active"]),
                "enforce": os.path.exists(ENFORCE_FILE),
            })
        elif u.path == "/admin/api/state":
            if not self.session_ok():
                return self.send_json(401, {"error": "로그인이 필요합니다"})
            with db() as c:
                keys = [dict(r) for r in c.execute("SELECT * FROM keys ORDER BY created DESC")]
                for k in keys:
                    k["devices"] = [dict(r) for r in c.execute(
                        "SELECT * FROM devices WHERE key=? ORDER BY activated", (k["key"],))]
            self.send_json(200, {"keys": keys, "enforce": os.path.exists(ENFORCE_FILE)})
        elif u.path == "/":
            self.send_response(302)
            self.send_header("Location", "/admin")
            self.end_headers()
        else:
            self.send_json(404, {"error": "not found"})

    def do_POST(self):
        u = urlparse(self.path)
        if self.headers.get("X-K2K") != "1":
            return self.send_json(400, {"error": "bad request"})
        body = self.read_json()
        if u.path == "/api/activate":
            return self.activate(body)
        if u.path == "/admin/login":
            return self.login(body)
        if not u.path.startswith("/admin/") or not self.session_ok():
            return self.send_json(401, {"error": "로그인이 필요합니다"})
        if u.path == "/admin/logout":
            c = SimpleCookie(self.headers.get("Cookie", ""))
            if c.get("k2k_admin"):
                with lock:
                    sessions.pop(c["k2k_admin"].value, None)
            return self.send_json(200, {"ok": True}, "k2k_admin=; Path=/; Max-Age=0; Secure; HttpOnly; SameSite=Strict")
        if u.path == "/admin/api/keys":
            key = new_key()
            mx = max(1, min(int(body.get("max_devices") or 3), 50))
            with db() as c:
                c.execute("INSERT INTO keys(key,name,max_devices,active,created) VALUES(?,?,?,1,?)",
                          (key, clean_text(body.get("name"), 60), mx, int(time.time())))
            return self.send_json(200, {"key": key})
        if u.path == "/admin/api/keys/toggle":
            with db() as c:
                c.execute("UPDATE keys SET active = 1 - active WHERE key=?", (norm_key(body.get("key")),))
            write_allow_list()
            return self.send_json(200, {"ok": True})
        if u.path == "/admin/api/keys/delete":
            k = norm_key(body.get("key"))
            with db() as c:
                c.execute("DELETE FROM devices WHERE key=?", (k,))
                c.execute("DELETE FROM keys WHERE key=?", (k,))
            write_allow_list()
            return self.send_json(200, {"ok": True})
        if u.path == "/admin/api/devices/delete":
            with db() as c:
                c.execute("DELETE FROM devices WHERE id=?", (clean_text(body.get("id"), 40),))
            write_allow_list()
            return self.send_json(200, {"ok": True})
        if u.path == "/admin/api/enforce":
            if body.get("on"):
                open(ENFORCE_FILE, "w").close()
            elif os.path.exists(ENFORCE_FILE):
                os.remove(ENFORCE_FILE)
            return self.send_json(200, {"ok": True})
        if u.path == "/admin/api/password":
            pw = str(body.get("password") or "")
            if len(pw) < 8:
                return self.send_json(400, {"error": "8자 이상으로 입력하세요"})
            set_password(pw)
            return self.send_json(200, {"ok": True})
        return self.send_json(404, {"error": "not found"})

    def login(self, body):
        ip = self.client_ip()
        now = time.time()
        with lock:
            cnt, first, until = login_fails.get(ip, (0, now, 0))
            if until > now:
                return self.send_json(429, {"error": "로그인 5회 실패로 15분간 잠겼습니다"})
        if check_password(str(body.get("password") or "")):
            tok = secrets.token_urlsafe(32)
            with lock:
                login_fails.pop(ip, None)
                sessions[tok] = now + SESSION_HOURS * 3600
            return self.send_json(200, {"ok": True},
                                  "k2k_admin=%s; Path=/; Max-Age=%d; Secure; HttpOnly; SameSite=Strict"
                                  % (tok, SESSION_HOURS * 3600))
        with lock:
            cnt = cnt + 1
            until = now + LOGIN_LOCK_SECONDS if cnt >= LOGIN_MAX_FAILS else 0
            login_fails[ip] = (0 if until else cnt, first, until)
        left = LOGIN_MAX_FAILS - cnt
        return self.send_json(401, {"error": "비밀번호가 틀렸습니다" + (" (남은 시도 %d회)" % left if left > 0 else " - 15분간 잠김")})

    def activate(self, body):
        ip = self.client_ip()
        now = time.time()
        with lock:
            hits = [t for t in activate_hits.get(ip, []) if now - t < ACTIVATE_WINDOW_SECONDS]
            if len(hits) >= ACTIVATE_MAX_PER_WINDOW:
                return self.send_json(429, {"error": "too_many"})
            hits.append(now)
            activate_hits[ip] = hits
        key = norm_key(body.get("key"))
        dev_id = clean_text(body.get("id"), 40)
        if not key or not re.fullmatch(r"[A-Za-z0-9_\-]{6,40}", dev_id or ""):
            return self.send_json(400, {"error": "invalid_key"})
        with db() as c:
            k = c.execute("SELECT * FROM keys WHERE key=?", (key,)).fetchone()
            if not k:
                return self.send_json(400, {"error": "invalid_key"})
            if not k["active"]:
                return self.send_json(403, {"error": "disabled"})
            cur = c.execute("SELECT key FROM devices WHERE id=?", (dev_id,)).fetchone()
            if not (cur and cur["key"] == key):
                used = c.execute("SELECT COUNT(*) n FROM devices WHERE key=?", (key,)).fetchone()["n"]
                if used >= k["max_devices"]:
                    return self.send_json(403, {"error": "limit"})
            c.execute(
                "INSERT INTO devices(id,key,name,platform,activated,last_seen) VALUES(?,?,?,?,?,?) "
                "ON CONFLICT(id) DO UPDATE SET key=excluded.key, name=excluded.name, "
                "platform=excluded.platform, last_seen=excluded.last_seen",
                (dev_id, key, clean_text(body.get("name"), 60), clean_text(body.get("platform"), 20),
                 int(now), int(now)),
            )
        write_allow_list()
        return self.send_json(200, {"ok": True})


def main():
    init_db()
    if not os.path.exists(ADMIN_FILE):
        pw = os.environ.get("K2K_ADMIN_PASSWORD") or secrets.token_urlsafe(9)
        set_password(pw)
        print("K2K admin password:", pw, flush=True)
    ThreadingHTTPServer((BIND, PORT), Handler).serve_forever()


if __name__ == "__main__":
    main()
