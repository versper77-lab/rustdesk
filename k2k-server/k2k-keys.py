sessions = {}  # token -> expiry
login_fails = {}  # ip -> (count, first_fail_time, locked_until)
activate_hits = {}  # ip -> [timestamps]


def db():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    os.makedirs(KEYS_DIR, exist_ok=True)
    with db() as c:
        c.execute(
            """CREATE TABLE IF NOT EXISTS keys (
                key TEXT PRIMARY KEY, name TEXT NOT NULL DEFAULT '',
                max_devices INTEGER NOT NULL DEFAULT 3,
                active INTEGER NOT NULL DEFAULT 1, created INTEGER NOT NULL)"""
        )
        c.execute(
            """CREATE TABLE IF NOT EXISTS devices (
                id TEXT PRIMARY KEY, key TEXT NOT NULL, name TEXT NOT NULL DEFAULT '',
                platform TEXT NOT NULL DEFAULT '', activated INTEGER NOT NULL,
                last_seen INTEGER NOT NULL)"""
        )
    write_allow_list()


def write_allow_list():
    with db() as c:
        rows = c.execute(
            "SELECT d.id FROM devices d JOIN keys k ON d.key = k.key WHERE k.active = 1"
        ).fetchall()
    tmp = ALLOW_FILE + ".tmp"
    with open(tmp, "w") as f:
        f.write("# generated by k2k-keys.py\n")
        for r in rows:
            f.write(r["id"] + "\n")
    os.replace(tmp, ALLOW_FILE)


def new_key():
    parts = ["".join(secrets.choice(KEY_ALPHABET) for _ in range(4)) for _ in range(3)]
    return "K2K-" + "-".join(parts)


def norm_key(k):
    k = re.sub(r"[^A-Za-z0-9]", "", (k or "")).upper()
    if k.startswith("K2K"):
        k = k[3:]
    if len(k) != 12:
        return ""
    return "K2K-%s-%s-%s" % (k[0:4], k[4:8], k[8:12])


def hash_password(pw, salt=None):
    salt = salt or secrets.token_hex(16)
    h = hashlib.pbkdf2_hmac("sha256", pw.encode(), salt.encode(), 200_000).hex()
    return {"salt": salt, "hash": h}


def check_password(pw):
    try:
        with open(ADMIN_FILE) as f:
            a = json.load(f)
    except (OSError, ValueError):
        return False
    return hmac.compare_digest(hash_password(pw, a["salt"])["hash"], a["hash"])


def set_password(pw):
    tmp = ADMIN_FILE + ".tmp"
    with open(tmp, "w") as f:
        json.dump(hash_password(pw), f)
    os.chmod(tmp, 0o600)
    os.replace(tmp, ADMIN_FILE)


def clean_text(s, n):
    return re.sub(r"[\x00-\x1f]", "", str(s or ""))[:n]


