def db():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    os.makedirs(KEYS_DIR, exist_ok=True)
    with db() as c:
        c.execute(
            """CREATE TABLE IF NOT EXISTS keys (
                key TEXT PRIMARY KEY, name TEXT NOT NULL DEFAULT '',
                max_devices INTEGER NOT NULL DEFAULT 3,
                active INTEGER NOT NULL DEFAULT 1, created INTEGER NOT NULL)"""
        )
        c.execute(
            """CREATE TABLE IF NOT EXISTS devices (
                id TEXT PRIMARY KEY, key TEXT NOT NULL, name TEXT NOT NULL DEFAULT '',
                platform TEXT NOT NULL DEFAULT '', activated INTEGER NOT NULL,
                last_seen INTEGER NOT NULL)"""
        )
        c.execute(
            "CREATE TABLE IF NOT EXISTS traffic (ts INTEGER NOT NULL, rx INTEGER NOT NULL, tx INTEGER NOT NULL)"
        )
    write_allow_list()


def write_allow_list():
    with db() as c:
        rows = c.execute(
            "SELECT d.id FROM devices d JOIN keys k ON d.key = k.key WHERE k.active = 1"
        ).fetchall()
    tmp = ALLOW_FILE + ".tmp"
    with open(tmp, "w") as f:
        f.write("# generated by k2k-keys.py\n")
        for r in rows:
            f.write(r["id"] + "\n")
    os.replace(tmp, ALLOW_FILE)


def new_key():
    parts = ["".join(secrets.choice(KEY_ALPHABET) for _ in range(4)) for _ in range(3)]
    return "K2K-" + "-".join(parts)


def norm_key(k):
    k = re.sub(r"[^A-Za-z0-9]", "", (k or "")).upper()
    if k.startswith("K2K"):
        k = k[3:]
    if len(k) != 12:
        return ""
    return "K2K-%s-%s-%s" % (k[0:4], k[4:8], k[8:12])


def hash_password(pw, salt=None):
    salt = salt or secrets.token_hex(16)
    h = hashlib.pbkdf2_hmac("sha256", pw.encode(), salt.encode(), 200_000).hex()
    return {"salt": salt, "hash": h}


def check_password(pw):
    try:
        with open(ADMIN_FILE) as f:
            a = json.load(f)
    except (OSError, ValueError):
        return False
    return hmac.compare_digest(hash_password(pw, a["salt"])["hash"], a["hash"])


def set_password(pw):
    tmp = ADMIN_FILE + ".tmp"
    with open(tmp, "w") as f:
        json.dump(hash_password(pw), f)
    os.chmod(tmp, 0o600)
    os.replace(tmp, ADMIN_FILE)


def clean_text(s, n):
    return re.sub(r"[\x00-\x1f]", "", str(s or ""))[:n]


# ---- server control (Docker Engine API over the mounted socket) ----
class _DockerConn(http.client.HTTPConnection):
    def __init__(self):
        super().__init__("localhost", timeout=30)

    def connect(self):
        s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        s.settimeout(30)
        s.connect(DOCKER_SOCK)
        self.sock = s


def docker(method, path):
    c = _DockerConn()
    try:
        c.request(method, path)
        r = c.getresponse()
        return r.status, r.read()
    finally:
        c.close()


def server_state():
    out = []
    for name in SERVER_CONTAINERS:
        try:
            code, data = docker("GET", "/containers/%s/json" % name)
            if code != 200:
                raise OSError(code)
            st = json.loads(data)["State"]
            out.append({"name": name, "running": bool(st.get("Running")),
                        "started": st.get("StartedAt", "")})
        except Exception:
            out.append({"name": name, "running": None, "started": ""})
    return out


def set_server(on):
    if on:
        if os.path.exists(SERVER_OFF_FILE):
            os.remove(SERVER_OFF_FILE)
    else:
        open(SERVER_OFF_FILE, "w").close()
    names = SERVER_CONTAINERS if on else tuple(reversed(SERVER_CONTAINERS))
    for name in names:
        code, data = docker("POST", "/containers/%s/%s" % (name, "start" if on else "stop?t=5"))
        if code not in (204, 304):
            raise OSError("%s: %s %s" % (name, code, data[:200].decode(errors="replace")))


def relay_requests_since(ts):
    """Counts hbbr 'New relay request' log lines since `ts` (one per side of a relayed session)."""
    try:
        code, data = docker("GET", "/containers/hbbr/logs?stdout=1&stderr=1&since=%d" % int(ts))
    except Exception:
        return None
    if code != 200:
        return None
    n, i = 0, 0
    while i + 8 <= len(data):  # multiplexed stream: 8-byte header + payload
        size = int.from_bytes(data[i + 4:i + 8], "big")
        n += data[i + 8:i + 8 + size].count(b"New relay request")
        i += 8 + size
    return n


